/*
Operadores relacionais

== -> igual
=== -> Estreitamente igual valor e tipo
!= diferente
> = maior
< = menor
>= = maior igual
<= = menor igual
*/

let num1 = 7
let num2 = "7"

console.log(num1 == num2)
console.log(num1 === num2)
console.log(num1 != num2)
console.log(num1 !== num2)
console.log(num1 >= num2)
console.log(num1 <= num2)
console.log(num1 > num2)
console.log(num1 < num2)